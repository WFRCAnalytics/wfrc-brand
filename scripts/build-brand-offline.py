"""Generate _extensions/wfrc-brand/brand-offline.yml from brand.yml.

Same brand, but typography.fonts points at the bundled files in assets/fonts (fetch them with
scripts/fetch-fonts.py). Run after any change to brand.yml:

    python scripts/build-brand-offline.py

Why a second file: a brand file has one source per font family, and Quarto 1.11 does not copy
bundled fonts for revealjs, so the Google default must stay the default.
"""
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent / "_extensions/wfrc-brand"
FAMILIES = {  # family -> (file prefix, weights, styles)
    "Poppins": ("Poppins", [400, 500, 600], ["normal", "italic"]),
    "Inter": ("Inter", [400, 500, 600, 700], ["normal"]),
    "Fira Code": ("FiraCode", [400, 500], ["normal"]),
}

src = (EXT / "brand.yml").read_text(encoding="utf-8")
start = src.index("typography:\n")
end = src.index("  base:\n    family:", start)

lines = [
    "typography:",
    "  # Bundled fonts (SIL OFL 1.1): no request to Google, works offline. woff2 serves the web and",
    "  # ttf serves Typst. Not for revealjs: Quarto does not copy bundled fonts there. Use brand.yml.",
    "  fonts:",
]
for fam, (prefix, weights, styles) in FAMILIES.items():
    lines += [f"    - family: {fam}", "      source: file", "      files:"]
    for st in styles:
        for w in weights:
            for ext in ("woff2", "ttf"):
                lines += [
                    f"        - path: assets/fonts/{prefix}-{w}-{st}.{ext}",
                    f"          weight: {w}",
                    f"          style: {st}",
                ]

header = (
    "# GENERATED by scripts/build-brand-offline.py from brand.yml. Do not edit by hand.\n"
    "# brand.yml with bundled fonts. Use: project.brand: _extensions/wfrc-brand/brand-offline.yml\n"
)
(EXT / "brand-offline.yml").write_text(header + src[:start] + "\n".join(lines) + "\n" + src[end:], encoding="utf-8")
print("wrote brand-offline.yml")
