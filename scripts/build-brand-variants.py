"""Generate the variants of brand.yml. Run after any change to brand.yml:

    python scripts/build-brand-variants.py

brand-offline.yml  typography.fonts points at the bundled files in assets/fonts (fetch them with
                   scripts/fetch-fonts.py). A brand file has one source per font family, and Quarto
                   1.11 does not copy bundled fonts for revealjs, so Google stays the default.
brand-flat.yml     every `light:`/`dark:` pair is replaced by its light value. The R and Python
                   brand.yml packages (Shiny, bslib, great-tables...) reject light/dark values,
                   which only Quarto 1.8+ understands.
"""
import re
from pathlib import Path

EXT = Path(__file__).resolve().parent.parent / "_extensions/WFRCAnalytics/wfrc-brand"
FAMILIES = {  # family -> (file prefix, weights, styles)
    "Poppins": ("Poppins", [400, 500, 600], ["normal", "italic"]),
    "Inter": ("Inter", [400, 500, 600, 700], ["normal"]),
    "Fira Code": ("FiraCode", [400, 500], ["normal"]),
}

src = (EXT / "brand.yml").read_text(encoding="utf-8")
start = src.index("typography:\n")
end = src.index("  base:\n    family:", start)

lines = [
    "typography:",
    "  # Bundled fonts (SIL OFL 1.1): no request to Google, works offline. woff2 serves the web and",
    "  # ttf serves Typst. Not for revealjs: Quarto does not copy bundled fonts there. Use brand.yml.",
    "  fonts:",
]
for fam, (prefix, weights, styles) in FAMILIES.items():
    lines += [f"    - family: {fam}", "      source: file", "      files:"]
    for st in styles:
        for w in weights:
            for ext in ("woff2", "ttf"):
                lines += [
                    f"        - path: assets/fonts/{prefix}-{w}-{st}.{ext}",
                    f"          weight: {w}",
                    f"          style: {st}",
                ]

header = (
    "# GENERATED by scripts/build-brand-variants.py from brand.yml. Do not edit by hand.\n"
    "# brand.yml with bundled fonts. Use: project.brand: _extensions/WFRCAnalytics/wfrc-brand/brand-offline.yml\n"
)
(EXT / "brand-offline.yml").write_text(header + src[:start] + "\n".join(lines) + "\n" + src[end:], encoding="utf-8")
print("wrote brand-offline.yml")

# A `key:` whose only children are `light:` and `dark:` becomes `key: <light value>`.
PAIR = re.compile(r"^( *)([\w-]+):[ \t]*\n\1  light: *(\S+)[ \t]*\n\1  dark: *\S+[ \t]*\n", re.M)
flat = PAIR.sub(r"\1\2: \3\n", src)
flat_header = (
    "# GENERATED by scripts/build-brand-variants.py from brand.yml. Do not edit by hand.\n"
    "# brand.yml with light values only, for tools whose brand.yml package has no light/dark support:\n"
    "# Shiny for R and Python, bslib, great-tables. Quarto sites should use brand.yml.\n"
)
(EXT / "brand-flat.yml").write_text(flat_header + flat, encoding="utf-8")
print("wrote brand-flat.yml")
